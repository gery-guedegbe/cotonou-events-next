export function getEventById(id: string): CotonouEvent | undefined {
  return EVENTS.find((e) => e.id === id);
}

export function getSimilarEvents(
  event: CotonouEvent,
  limit = 3,
): CotonouEvent[] {
  return EVENTS.filter(
    (e) => e.category === event.category && e.id !== event.id,
  ).slice(0, limit);
}
